-- Aplicar uma vez em bancos existentes antes do deploy da persistencia de Ecos (PR 3).
-- Pre-requisito: 009_add_account_reactivation.sql (independente da 010, que permanece reservada).
BEGIN;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM Listens LIMIT 1) THEN
        RAISE EXCEPTION 'Migration 012 requires an empty Listens table before adding NOT NULL track_id.';
    END IF;
END $$;

ALTER TABLE Artists
    ALTER COLUMN name TYPE VARCHAR(500);

ALTER TABLE Albums
    ALTER COLUMN name TYPE VARCHAR(500);

CREATE TABLE Tracks (
    track_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spotify_id VARCHAR(64) NOT NULL UNIQUE,
    album_id BIGINT NOT NULL
        REFERENCES Albums(album_id) ON DELETE RESTRICT,
    name VARCHAR(500) NOT NULL,
    duration_ms INTEGER,
    explicit BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_track_duration CHECK (duration_ms IS NULL OR duration_ms >= 0)
);

CREATE TABLE Track_Artists (
    track_id BIGINT NOT NULL
        REFERENCES Tracks(track_id) ON DELETE CASCADE,
    position SMALLINT NOT NULL,
    artist_id BIGINT NOT NULL
        REFERENCES Artists(artist_id) ON DELETE RESTRICT,
    PRIMARY KEY (track_id, position),
    CONSTRAINT uk_track_artist UNIQUE (track_id, artist_id),
    CONSTRAINT chk_track_artist_position CHECK (position >= 0)
);

ALTER TABLE Listens
    ADD COLUMN track_id BIGINT NOT NULL
        REFERENCES Tracks(track_id) ON DELETE RESTRICT;

CREATE INDEX idx_listens_user_played_desc
    ON Listens (user_id, played_at DESC, listen_id DESC);

CREATE TABLE echo_sync_state (
    user_id BIGINT PRIMARY KEY
        REFERENCES Users(user_id) ON DELETE CASCADE,
    next_allowed_at TIMESTAMP WITH TIME ZONE,
    lease_until TIMESTAMP WITH TIME ZONE,
    last_succeeded_at TIMESTAMP WITH TIME ZONE,
    history_starts_at TIMESTAMP WITH TIME ZONE
);

COMMIT;
