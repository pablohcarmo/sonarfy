CREATE TABLE Permissions (
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission VARCHAR(50) NOT NULL UNIQUE
);

INSERT INTO Permissions (permission) VALUES
('ROLE_ADMIN'),
('ROLE_MODERATOR'),
('ROLE_USER');

CREATE TABLE Users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_id BIGINT NOT NULL
        REFERENCES Permissions(permission_id) ON DELETE RESTRICT,
    name VARCHAR(50) NOT NULL,
    surname VARCHAR(50) NOT NULL,
    display_name VARCHAR(60) NOT NULL,
    handle VARCHAR(15) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    country VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    avatar VARCHAR(255),
    wallpaper VARCHAR(255),
    biography VARCHAR(150),
    birth_date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    password_updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_email_sent_at TIMESTAMP WITH TIME ZONE,
    spotify_authorization_version BIGINT NOT NULL DEFAULT 0,
    access_token_version BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uk_users_email_ci ON Users (lower(email));
CREATE UNIQUE INDEX uk_users_handle_ci ON Users (lower(handle));

CREATE TABLE User_Following (
    follower_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE CASCADE,
    following_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE CASCADE,
    follow_date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (follower_id, following_id),
    CONSTRAINT chk_no_self_follow CHECK (follower_id <> following_id)
);

CREATE INDEX idx_user_following_following_follower ON User_Following (following_id, follower_id);

CREATE TABLE Spotify_Connection (
    connection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE
        REFERENCES Users(user_id) ON DELETE CASCADE,
    access_token_encrypted TEXT,
    refresh_token_encrypted TEXT,
    status VARCHAR(32) NOT NULL DEFAULT 'CONNECTED',
    authorization_generation BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT spotify_connection_status_tokens CHECK (
        (status = 'CONNECTED' AND access_token_encrypted IS NOT NULL AND refresh_token_encrypted IS NOT NULL)
        OR (status = 'REAUTHORIZATION_REQUIRED' AND access_token_encrypted IS NULL AND refresh_token_encrypted IS NULL)),
    token_type VARCHAR(255) NOT NULL,
    scopes TEXT,
    access_token_expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    connected_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Integration_Events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE RESTRICT,
    event_type VARCHAR(30) NOT NULL,
    event_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_integration_event_type
        CHECK (event_type IN ('CONNECTED', 'DISCONNECTED'))
);

CREATE TABLE Artists (
    artist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spotify_id VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(500) NOT NULL,
    avatar VARCHAR(255)
);

CREATE TABLE Albums (
    album_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id BIGINT NOT NULL
        REFERENCES Artists(artist_id) ON DELETE RESTRICT,
    spotify_id VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(500) NOT NULL,
    length_seconds INTEGER,
    cover VARCHAR(255),
    release_on VARCHAR(10),
    release_date_precision VARCHAR(5),
    CONSTRAINT chk_album_length CHECK (length_seconds >= 0),
    CONSTRAINT chk_release_precision CHECK (
        (release_on IS NULL AND release_date_precision IS NULL)
        OR (
            release_on IS NOT NULL
            AND release_date_precision IS NOT NULL
            AND (
                (release_date_precision = 'ano'
                    AND release_on ~ '^[0-9]{4}$')
                OR (release_date_precision = 'mes'
                    AND release_on ~ '^[0-9]{4}-(0[1-9]|1[0-2])$')
                OR (release_date_precision = 'dia'
                    AND release_on ~ '^[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])$')
            )
        )
    )
);

CREATE TABLE Reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id BIGINT NOT NULL
        REFERENCES Albums(album_id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE CASCADE,
    rating NUMERIC(3,1) NOT NULL,
    review_text VARCHAR(255),
    is_favorite BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_review_user_album UNIQUE (user_id, album_id),
    CONSTRAINT chk_rating_range CHECK (rating BETWEEN 0 AND 10),
    CONSTRAINT chk_rating_step CHECK (mod(rating, 0.5) = 0)
);

CREATE TABLE Access_Logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE RESTRICT,
    ip_address VARCHAR(45) NOT NULL,
    logged_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Tracks (
    track_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spotify_id VARCHAR(64) NOT NULL UNIQUE,
    album_id BIGINT NOT NULL
        REFERENCES Albums(album_id) ON DELETE RESTRICT,
    name VARCHAR(500) NOT NULL,
    duration_ms INTEGER,
    explicit BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_track_duration CHECK (duration_ms IS NULL OR duration_ms >= 0)
);

CREATE TABLE Track_Artists (
    track_id BIGINT NOT NULL
        REFERENCES Tracks(track_id) ON DELETE CASCADE,
    position SMALLINT NOT NULL,
    artist_id BIGINT NOT NULL
        REFERENCES Artists(artist_id) ON DELETE RESTRICT,
    PRIMARY KEY (track_id, position),
    CONSTRAINT uk_track_artist UNIQUE (track_id, artist_id),
    CONSTRAINT chk_track_artist_position CHECK (position >= 0)
);

CREATE TABLE Listens (
    listen_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE CASCADE,
    album_id BIGINT NOT NULL
        REFERENCES Albums(album_id) ON DELETE RESTRICT,
    track_id BIGINT NOT NULL
        REFERENCES Tracks(track_id) ON DELETE RESTRICT,
    spotify_track_id VARCHAR(255) NOT NULL,
    played_at TIMESTAMP WITH TIME ZONE NOT NULL,
    imported_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_listen_event
        UNIQUE (user_id, spotify_track_id, played_at)
);

CREATE INDEX idx_listens_user_played_desc
    ON Listens (user_id, played_at DESC, listen_id DESC);

CREATE TABLE echo_sync_state (
    user_id BIGINT PRIMARY KEY
        REFERENCES Users(user_id) ON DELETE CASCADE,
    next_allowed_at TIMESTAMP WITH TIME ZONE,
    lease_until TIMESTAMP WITH TIME ZONE,
    lease_id UUID,
    last_succeeded_at TIMESTAMP WITH TIME ZONE,
    history_starts_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE refresh_tokens (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    session_id UUID NOT NULL,
    used_at TIMESTAMP WITH TIME ZONE,
    remember_me BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);

CREATE INDEX idx_refresh_tokens_session_id ON refresh_tokens (session_id);

CREATE TABLE email_change_requests (
    user_id BIGINT PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
    request_id UUID NOT NULL UNIQUE,
    new_email VARCHAR(150) NOT NULL,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    CHECK (expires_at > issued_at)
);
CREATE TABLE email_change_mail_outbox (
    event_id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    request_id UUID NOT NULL,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('CONFIRM_NEW_EMAIL', 'NOTIFY_OLD_EMAIL')),
    recipient VARCHAR(150) NOT NULL,
    available_at TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    lease_id UUID,
    lease_until TIMESTAMP WITH TIME ZONE,
    delivered_at TIMESTAMP WITH TIME ZONE,
    CHECK ((lease_id IS NULL) = (lease_until IS NULL))
);
CREATE INDEX idx_email_change_mail_pending ON email_change_mail_outbox (available_at)
    WHERE delivered_at IS NULL;

CREATE TABLE reactivation_mail_outbox (
    event_id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    recipient VARCHAR(150) NOT NULL,
    available_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_id UUID,
    lease_until TIMESTAMP WITH TIME ZONE,
    delivered_at TIMESTAMP WITH TIME ZONE,
    CHECK ((lease_id IS NULL) = (lease_until IS NULL))
);
CREATE INDEX idx_reactivation_mail_pending ON reactivation_mail_outbox (available_at)
    WHERE delivered_at IS NULL;
