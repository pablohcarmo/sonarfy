CREATE TABLE Permissions (
    permission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission VARCHAR(50) NOT NULL UNIQUE
);

INSERT INTO Permissions (permission) VALUES
('ROLE_ADMIN'),
('ROLE_MODERATOR'),
('ROLE_USER');

CREATE TABLE Users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_id BIGINT NOT NULL
        REFERENCES Permissions(permission_id) ON DELETE RESTRICT,
    name VARCHAR(50) NOT NULL,
    surname VARCHAR(50) NOT NULL,
    display_name VARCHAR(60) NOT NULL,
    handle VARCHAR(15) NOT NULL,
    email VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    country VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    avatar VARCHAR(255),
    wallpaper VARCHAR(255),
    biography VARCHAR(150),
    birth_date DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    password_updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_email_sent_at TIMESTAMP WITH TIME ZONE,
    spotify_authorization_version BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uk_users_email_ci ON Users (lower(email));
CREATE UNIQUE INDEX uk_users_handle_ci ON Users (lower(handle));

CREATE TABLE User_Following (
    follower_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE CASCADE,
    following_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE CASCADE,
    follow_date TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (follower_id, following_id),
    CONSTRAINT chk_no_self_follow CHECK (follower_id <> following_id)
);

CREATE TABLE Spotify_Connection (
    connection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE
        REFERENCES Users(user_id) ON DELETE CASCADE,
    access_token_encrypted TEXT NOT NULL,
    refresh_token_encrypted TEXT NOT NULL,
    token_type VARCHAR(255) NOT NULL,
    scopes TEXT,
    access_token_expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    connected_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Integration_Events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE RESTRICT,
    event_type VARCHAR(30) NOT NULL,
    event_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_integration_event_type
        CHECK (event_type IN ('CONNECTED', 'DISCONNECTED'))
);

CREATE TABLE Artists (
    artist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spotify_id VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    avatar VARCHAR(255)
);

CREATE TABLE Albums (
    album_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id BIGINT NOT NULL
        REFERENCES Artists(artist_id) ON DELETE RESTRICT,
    spotify_id VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    length_seconds INTEGER,
    cover VARCHAR(255),
    release_on VARCHAR(10),
    release_date_precision VARCHAR(5),
    CONSTRAINT chk_album_length CHECK (length_seconds >= 0),
    CONSTRAINT chk_release_precision CHECK (
        (release_on IS NULL AND release_date_precision IS NULL)
        OR (
            release_on IS NOT NULL
            AND release_date_precision IS NOT NULL
            AND (
                (release_date_precision = 'ano'
                    AND release_on ~ '^[0-9]{4}$')
                OR (release_date_precision = 'mes'
                    AND release_on ~ '^[0-9]{4}-(0[1-9]|1[0-2])$')
                OR (release_date_precision = 'dia'
                    AND release_on ~ '^[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01])$')
            )
        )
    )
);

CREATE TABLE Reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id BIGINT NOT NULL
        REFERENCES Albums(album_id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE CASCADE,
    rating NUMERIC(3,1) NOT NULL,
    review_text VARCHAR(255),
    is_favorite BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_review_user_album UNIQUE (user_id, album_id),
    CONSTRAINT chk_rating_range CHECK (rating BETWEEN 0 AND 10),
    CONSTRAINT chk_rating_step CHECK (mod(rating, 0.5) = 0)
);

CREATE TABLE Access_Logs (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE RESTRICT,
    ip_address VARCHAR(45) NOT NULL,
    logged_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Listens (
    listen_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE CASCADE,
    album_id BIGINT NOT NULL
        REFERENCES Albums(album_id) ON DELETE RESTRICT,
    spotify_track_id VARCHAR(255) NOT NULL,
    played_at TIMESTAMP WITH TIME ZONE NOT NULL,
    imported_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_listen_event
        UNIQUE (user_id, spotify_track_id, played_at)
);

CREATE TABLE Refresh_Tokens (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES Users(user_id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_refresh_tokens_user_id ON Refresh_Tokens (user_id);
